import { expect, test } from '@playwright/test'
import { CUENTAS, conectarDb, leerCola, loginEnApp } from '../helpers/e2e'

test('la desconexión y recuperación reales se detectan sin intervención manual', async ({ page, context }) => {
  await loginEnApp(page, CUENTAS.trabajadorA)
  const signal = page.getByRole('switch', { name: /señal/i })
  await expect(signal).toHaveAttribute('aria-checked', 'true')
  await context.setOffline(true)
  await expect(signal).toHaveAttribute('aria-checked', 'false')
  await context.setOffline(false)
  await expect(signal).toHaveAttribute('aria-checked', 'true')
})

test('sin señal manual persiste entre renders, navegación, recarga y reconexión física', async ({ page, context }) => {
  await loginEnApp(page, CUENTAS.trabajadorA)
  const signal = page.getByRole('switch', { name: /señal/i })
  await expect(signal).toHaveAttribute('aria-checked', 'true')
  await signal.click()
  await expect(signal).toHaveAttribute('aria-checked', 'false')
  const text = `Regresión de señal ${Date.now()}`
  const db = await conectarDb()
  const count = () => db.contar('SELECT count(*)::int AS n FROM log_entry WHERE entry_text=$1', [text])
  await page.getByRole('button', { name: 'Bitácora', exact: true }).click()
  await page.getByRole('button', { name: 'Nueva entrada' }).click()
  await page.locator('textarea').fill(text)
  await page.getByRole('button', { name: 'Guardar entrada' }).click()
  await expect.poll(async () => (await leerCola(page)).pendientes).toBe(1)
  expect(await count()).toBe(0)
  await page.getByRole('button', { name: 'Cola', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Cola de sincronización' })).toBeVisible()
  await expect(signal).toHaveAttribute('aria-checked', 'false')
  await page.reload()
  await expect(signal).toHaveAttribute('aria-checked', 'false')
  expect((await leerCola(page)).pendientes).toBe(1)
  await context.setOffline(true)
  await context.setOffline(false)
  await expect(signal).toHaveAttribute('aria-checked', 'false')
  expect(await count()).toBe(0)
  await signal.click()
  await expect(signal).toHaveAttribute('aria-checked', 'true')
  await expect.poll(count).toBe(1)
  await expect.poll(async () => (await leerCola(page)).pendientes).toBe(0)
  await page.reload()
  await expect(signal).toHaveAttribute('aria-checked', 'true')
  expect(await count()).toBe(1)
})
